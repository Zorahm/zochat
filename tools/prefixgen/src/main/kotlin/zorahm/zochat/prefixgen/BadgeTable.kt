package zorahm.zochat.prefixgen

/** badges.yml for zoChat: which character in the zochat:badges font is which badge, plus text labels. */
object BadgeTable {
    fun yaml(ranks: List<Rank>): String = buildString {
        append("# Generated by tools/prefixgen (./gradlew :prefixgen:run) - rerun it instead of editing by hand.\n")
        append("# The character of every badge in the resource pack font; zoChat's <badge:id> tag reads this.\n")
        append("# Labels are the text shown instead of the glyph where there is no resource pack (console, badges off).\n")
        append("font: \"${ResourcePack.FONT}\"\n")
        append("badges:\n")
        for (rank in ranks) {
            append("  ${rank.id}:\n")
            append("    label-en: \"${rank.en}\"\n")
            append("    label-ru: \"${rank.ru}\"\n")
            for (variant in Variant.entries) {
                append("    ${variant.dir}: \"${"%04X".format(rank.codepoint(variant))}\"\n")
            }
        }
    }
}
